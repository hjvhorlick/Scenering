export function getFilterPreset(filterId?: SceneFilterType): FilterPreset {
  if (!filterId || filterId === "none") {
    return REAL_FILTER_PRESETS[REAL_FILTER_PRESETS.length - 1]; // "none"
  }
  return REAL_FILTER_PRESETS.find((f) => f.id === filterId) || REAL_FILTER_PRESETS[0];
}

export function getCssFilterString(filterId?: SceneFilterType): string {
  const preset = getFilterPreset(filterId);
  return preset.cssFilter;
}

export function getCanvasFilterString(filterId?: SceneFilterType): string {
  const preset = getFilterPreset(filterId);
  return preset.canvasFilter;
}
